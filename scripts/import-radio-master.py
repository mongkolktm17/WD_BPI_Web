#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Import radio master data from legacy Excel (รายการวิทยุ 20260914.xlsx)
into PostgreSQL `radio_equipments` table.

Usage:
    python scripts/import-radio-master.py [--sql-out tmp/radio_master_seed.sql] [--xlsx legacy/Backup]
    python scripts/import-radio-master.py --apply "postgresql://user:pass@host:5432/db"   # needs psycopg2

Default mode only *generates* the seed SQL (safe). The generated SQL is
idempotent (INSERT ... ON CONFLICT(asset_number) DO UPDATE).

Excel layout (sheet "วิทยุ"):
    col A: ลำดับ | col B: Asset number | col C: Description | col D: Serial number
"""
import argparse
import os
import re
import sys

IMAGE_BY_FAMILY = {
    "motorola-cp246": "/report_assets/radio/motorola-cp246.jpg",
    "icom-fx": "/report_assets/radio/icom-fx.jpg",
    "hytera-p30": "/report_assets/radio/hytera-p30.jpg",
    "spender-tm581": "/report_assets/radio/spender-tm581dtv.jpg",
    "generic": None,
}


def classify(description: str):
    """Return (brand, model, family) from free-text description."""
    d = (description or "").strip()
    u = d.upper()
    if "MOTOROLA" in u:
        m = re.search(r"CP-?\s?(\d+[A-Z]*)", u)
        return ("Motorola", f"CP-{m.group(1)}" if m else "CP246", "motorola-cp246")
    if "HYTERA" in u:
        m = re.search(r"P\d+[A-Z]*", u)
        return ("Hytera", m.group(0) if m else "P30", "hytera-p30")
    if "SPENDER" in u:
        m = re.search(r"TM-?\s?\d+\s?[A-Z]*(?:DTV)?", u)
        model = m.group(0).replace(" ", "") if m else "TM-581DTV"
        return ("Spender", model, "spender-tm581")
    if "ICOM" in u:
        m = re.search(r"(IC-)?(\d+)\s*FX", u)
        model = f"IC-{m.group(2)}FX" if m else "ICOM"
        return ("Icom", model, "icom-fx")
    return (d.split()[0] if d else "Unknown", d[:50], "generic")


def sql_escape(s: str) -> str:
    return s.replace("'", "''")


def find_workbook(backup_dir: str) -> str:
    for f in sorted(os.listdir(backup_dir)):
        if f.endswith(".xlsx") and not os.path.basename(f).startswith("~"):
            return os.path.join(backup_dir, f)
    raise FileNotFoundError(f"No .xlsx found in {backup_dir}")


def read_rows(xlsx_path: str):
    import openpyxl  # pip install openpyxl

    wb = openpyxl.load_workbook(xlsx_path, data_only=True, read_only=True)
    ws = wb[wb.sheetnames[0]]
    rows = []
    empty_run = 0
    for i, row in enumerate(ws.iter_rows(values_only=True)):
        if i == 0:
            continue  # header
        asset, desc, serial = row[1], row[2], row[3]
        if asset is None and desc is None and serial is None:
            empty_run += 1
            if empty_run > 200:
                break
            continue
        empty_run = 0
        if asset is None:
            print(f"WARN: skip row {i + 1}: missing Asset number ({desc})", file=sys.stderr)
            continue
        rows.append({
            "asset": str(asset).strip(),
            "desc": str(desc).strip() if desc is not None else "",
            "serial": str(serial).strip() if serial is not None else "",
        })
    wb.close()
    return rows


def to_sql(rows) -> str:
    lines = [
        "-- Radio master seed (generated by scripts/import-radio-master.py)",
        "-- Source: legacy/Backup/รายการวิทยุ 20260914.xlsx",
        "INSERT INTO radio_equipments (asset_number, asset_name, brand, model, serial_number, reference_image_url, status, site_id) VALUES",
    ]
    vals = []
    for r in rows:
        brand, model, family = classify(r["desc"])
        img = IMAGE_BY_FAMILY[family]
        img_sql = f"'{img}'" if img else "NULL"
        serial_sql = f"'{sql_escape(r['serial'])}'" if r["serial"] else "NULL"
        vals.append(
            f"('{sql_escape(r['asset'])}', '{sql_escape(r['desc'])}', "
            f"'{sql_escape(brand)}', '{sql_escape(model)}', {serial_sql}, {img_sql}, 'active', 1)"
        )
    lines.append(",\n".join(vals))
    lines.append(
        "ON CONFLICT (asset_number) DO UPDATE SET asset_name = EXCLUDED.asset_name, "
        "brand = EXCLUDED.brand, model = EXCLUDED.model, serial_number = EXCLUDED.serial_number, "
        "reference_image_url = EXCLUDED.reference_image_url;"
    )
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--xlsx", default=None, help="Path to .xlsx file or Backup dir")
    ap.add_argument("--sql-out", default=os.path.join("tmp", "radio_master_seed.sql"))
    args = ap.parse_args()

    src = args.xlsx or os.path.join("legacy", "Backup")
    xlsx = src if src.lower().endswith(".xlsx") else find_workbook(src)
    print(f"Reading: {xlsx}")
    rows = read_rows(xlsx)
    print(f"Rows: {len(rows)}")
    if not rows:
        print("No data rows found.", file=sys.stderr)
        return 1
    sql = to_sql(rows)
    os.makedirs(os.path.dirname(args.sql_out) or ".", exist_ok=True)
    with open(args.sql_out, "w", encoding="utf-8") as f:
        f.write(sql)
    print(f"Wrote: {args.sql_out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
